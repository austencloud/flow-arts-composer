#!/usr/bin/env node
// Generates src/lib/shared/ui/color-presets.ts: 12 hues x 4 rows chosen in
// OKLCH so every swatch in a row has the same perceived lightness, then
// converted to sRGB hex. Run by hand after changing the tables below:
//   node scripts/generate-color-presets.mjs
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const HUES = [
  { hue: 25, name: "red" },
  { hue: 55, name: "orange" },
  { hue: 85, name: "gold" },
  { hue: 115, name: "yellow" },
  { hue: 145, name: "green" },
  { hue: 175, name: "teal" },
  { hue: 205, name: "cyan" },
  { hue: 235, name: "sky" },
  { hue: 265, name: "blue" },
  { hue: 295, name: "violet" },
  { hue: 325, name: "magenta" },
  { hue: 355, name: "pink" },
];

const COLOR_ROWS = [
  { row: "light", lightness: 0.82, chroma: 0.11, label: (n) => `Light ${n}` },
  { row: "vivid", cusp: true, label: (n) => capitalize(n) },
  { row: "deep", lightness: 0.48, chroma: 0.16, label: (n) => `Deep ${n}` },
];

function capitalize(word) {
  return word[0].toUpperCase() + word.slice(1);
}

// Björn Ottosson's Oklab matrices: https://bottosson.github.io/posts/oklab/
function oklchToLinearSrgb(L, C, hueDegrees) {
  const h = (hueDegrees * Math.PI) / 180;
  const a = C * Math.cos(h);
  const b = C * Math.sin(h);
  const l = (L + 0.3963377774 * a + 0.2158037573 * b) ** 3;
  const m = (L - 0.1055613458 * a - 0.0638541728 * b) ** 3;
  const s = (L - 0.0894841775 * a - 1.291485548 * b) ** 3;
  return [
    4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s,
    -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s,
    -0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s,
  ];
}

function inGamut(rgb) {
  return rgb.every((channel) => channel >= -1e-6 && channel <= 1 + 1e-6);
}

function toGammaByte(linear) {
  const clamped = Math.min(1, Math.max(0, linear));
  const gamma =
    clamped <= 0.0031308
      ? 12.92 * clamped
      : 1.055 * clamped ** (1 / 2.4) - 0.055;
  return Math.round(gamma * 255);
}

function maxChromaAt(L, hue) {
  let chroma = 0;
  while (chroma < 0.4 && inGamut(oklchToLinearSrgb(L, chroma + 0.002, hue))) chroma += 0.002;
  return chroma;
}

// The most saturated sRGB color of a hue: the gamut cusp. Yellow lives near
// L 0.97, blue near L 0.45, so a fixed lightness cannot hold a real rainbow.
function cuspHex(hue) {
  let best = { lightness: 0.66, chroma: 0 };
  for (let lightness = 0.3; lightness <= 0.97; lightness += 0.005) {
    const chroma = maxChromaAt(lightness, hue);
    if (chroma > best.chroma) best = { lightness, chroma };
  }
  return oklchToHex(best.lightness, best.chroma, hue);
}

// Walks chroma down until the color fits sRGB; hue and lightness stay put.
function oklchToHex(L, C, hue) {
  // Achromatic special case: at C=0, hue is meaningless and floating-point
  // matrix roundoff can nudge a channel a hair past 0 or 1. Route L=1/L=0
  // straight to pure white/black so the neutral row's endpoints are exact.
  if (C === 0) {
    if (L >= 1) return "#ffffff";
    if (L <= 0) return "#000000";
  }
  let chroma = C;
  let rgb = oklchToLinearSrgb(L, chroma, hue);
  while (!inGamut(rgb) && chroma > 0) {
    chroma = Math.max(0, chroma - 0.002);
    rgb = oklchToLinearSrgb(L, chroma, hue);
  }
  return `#${rgb.map((channel) => toGammaByte(channel).toString(16).padStart(2, "0")).join("")}`;
}

const presets = [];
for (const { row, lightness, chroma, cusp, label } of COLOR_ROWS) {
  for (const { hue, name } of HUES) {
    const hex = cusp ? cuspHex(hue) : oklchToHex(lightness, chroma, hue);
    presets.push({ hex, name: label(name), row });
  }
}
for (let step = 0; step < HUES.length; step += 1) {
  const lightness = 1 - step / (HUES.length - 1);
  const name =
    step === 0 ? "White" : step === HUES.length - 1 ? "Black" : `Grey ${Math.round(lightness * 100)}`;
  presets.push({ hex: oklchToHex(lightness, 0, 0), name, row: "neutral" });
}

const lines = presets.map(
  ({ hex, name, row }) => `  { hex: "${hex}", name: "${name}", row: "${row}" },`
);
const source = `// Generated by scripts/generate-color-presets.mjs. Do not edit by hand.
// 12 hues x 4 rows (light, vivid, deep, neutral) chosen in OKLCH. The light
// and deep rows share one perceived lightness; the vivid row sits at each
// hue's gamut cusp (its most saturated sRGB color). 48 divides by 12, 8 and
// 6, so the swatch grid never ends on a short row.
export type ColorPresetRow = "light" | "vivid" | "deep" | "neutral";

export interface ColorPreset {
  readonly hex: string;
  readonly name: string;
  readonly row: ColorPresetRow;
}

export const COLOR_PRESET_COLUMNS = ${HUES.length};

export const COLOR_PRESETS: readonly ColorPreset[] = [
${lines.join("\n")}
];
`;

const target = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "../src/lib/shared/ui/color-presets.ts"
);
writeFileSync(target, source);
console.log(`wrote ${presets.length} presets to ${target}`);
