#!/usr/bin/env node
/**
 * Run `svelte-kit sync` only when it would actually change something.
 *
 * WHY THIS EXISTS
 *
 * `svelte-kit sync` is destructive: it deletes `.svelte-kit/types/**` and
 * writes it back. Measured on this repo, `proxy+layout.server.ts` is missing
 * for ~47 ms every run. The dev server on :5173 stats that file to render any
 * route that uses the root layout, so a request landing inside that window
 * gets:
 *
 *   500  ENOENT: no such file or directory, stat
 *        'E:\tka-platform\.svelte-kit\types\src\routes\proxy+layout.server.ts'
 *
 * That error is not a broken dev server and not a bad route. It is a different
 * process having briefly deleted the file out from under a healthy one.
 *
 * `check`, `check:fast`, `check:watch` and every `build` all began with
 * `svelte-kit sync`, and the project rules require agents to run a check before
 * claiming work done. With several sessions running at once, Austen's dev
 * server was being handed a fresh 47 ms outage several times an hour, all day.
 *
 * THE OBSERVATION
 *
 * The generated types depend on the SHAPE of the route tree — which `+page`,
 * `+layout`, and `+server` files exist and where — not on their contents. A
 * proxy module just re-exports the real one. So editing a route's body, which
 * is what actually happens between two checks, cannot change a single
 * generated byte. Routes are added or removed maybe a few times a day; checks
 * run constantly.
 *
 * So: fingerprint the inputs that can change the output, skip the sync when
 * the fingerprint matches, and the outage window disappears for the ~99% of
 * runs that were pure churn. When routes DO change, one sync runs — at a moment
 * when the dev server is already reloading for the same edit.
 *
 * Concurrent runs take a lock rather than overlapping, because two syncs
 * interleaving widens the window instead of narrowing it.
 *
 * Usage:  node scripts/svelte-kit-sync-if-needed.mjs [--force]
 */

import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import {
  mkdirSync,
  readFileSync,
  readdirSync,
  rmSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { isSvelteKitGeneratedStateIntact } from "./lib/svelte-kit-generated-state.mjs";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUT_DIR = join(ROOT, ".svelte-kit");
const FINGERPRINT = join(OUT_DIR, ".sync-fingerprint");
const LOCK = join(OUT_DIR, ".sync-lock");
const ROUTES = join(ROOT, "src", "routes");

const force = process.argv.includes("--force");

/** Every route file whose PRESENCE shapes the generated types. */
function routeManifest(dir, acc = []) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) {
      routeManifest(full, acc);
    } else if (entry.name.startsWith("+")) {
      acc.push(relative(ROOT, full).replace(/\\/g, "/"));
    }
  }
  return acc;
}

function read(path) {
  try {
    return readFileSync(path, "utf8");
  } catch {
    return "";
  }
}

function installedKitVersion() {
  try {
    return JSON.parse(
      read(join(ROOT, "node_modules", "@sveltejs", "kit", "package.json"))
    ).version;
  } catch {
    return "unknown";
  }
}

function fingerprint() {
  const hash = createHash("sha1");
  // Route shape. Sorted so directory-read order can never flip the hash.
  hash.update(routeManifest(ROUTES).sort().join("\n"));
  // The sveltekit() options in vite.config.ts own outDir and the adapter, and
  // src/env.ts declares the env modules — all of which change what sync writes.
  hash.update(read(join(ROOT, "vite.config.ts")));
  hash.update(read(join(ROOT, "src", "env.ts")));
  // A Kit upgrade can change the generator itself.
  hash.update(installedKitVersion());
  return hash.digest("hex");
}

/**
 * The generated tree sync is responsible for. If any of this is missing the
 * fingerprint is meaningless — something deleted the output.
 */
function outputIntact() {
  return isSvelteKitGeneratedStateIntact(OUT_DIR);
}

function runSync() {
  // `shell: true` is required, not incidental: Node refuses to spawn a `.cmd`
  // directly on Windows, and does it by failing the spawn rather than throwing,
  // so without the shell this exits 1 with no output at all.
  const result = spawnSync("npx svelte-kit sync", {
    cwd: ROOT,
    stdio: "inherit",
    shell: true,
  });
  if (result.status !== 0) {
    process.exit(result.status ?? 1);
  }
}

/**
 * Hold the lock across the sync. A stale lock — a crashed run — is reclaimed
 * after 90 s rather than deadlocking every future check.
 */
function withLock(fn) {
  const STALE_MS = 90_000;
  const deadline = Date.now() + STALE_MS;
  for (;;) {
    try {
      writeFileSync(LOCK, String(process.pid), { flag: "wx" });
      break;
    } catch {
      const age = Date.now() - (statMtime(LOCK) ?? 0);
      if (age > STALE_MS) {
        rmSync(LOCK, { force: true });
        continue;
      }
      if (Date.now() > deadline) {
        // Never block a check forever on a lock we cannot explain.
        break;
      }
      sleep(100);
    }
  }
  try {
    fn();
  } finally {
    rmSync(LOCK, { force: true });
  }
}

function statMtime(path) {
  try {
    return statSync(path).mtimeMs;
  } catch {
    return null;
  }
}

function sleep(ms) {
  Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, ms);
}

mkdirSync(OUT_DIR, { recursive: true });

const current = fingerprint();

if (!force && outputIntact() && read(FINGERPRINT).trim() === current) {
  // Nothing that shapes the generated types has moved. Leave the dev server's
  // files alone.
  process.exit(0);
}

withLock(() => {
  // Re-check inside the lock: another session may have just synced the same
  // change while we waited.
  if (!force && outputIntact() && read(FINGERPRINT).trim() === current) return;
  runSync();
  writeFileSync(FINGERPRINT, `${fingerprint()}\n`);
});
