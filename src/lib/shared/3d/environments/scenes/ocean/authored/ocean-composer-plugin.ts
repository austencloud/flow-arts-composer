const allItems = categories.flatMap((c) => c.items);

const catalog: ComposerCatalog = {
  categories,
  getDefinition(key: string) {
    return allItems.find((d) => d.key === key);
  },
  allItems() {
    return allItems;
  },
};

const surfaceRules: SurfaceRules = {
  isSurface(mesh: Mesh): boolean {
    const name = (mesh.name ?? "").toLowerCase();
    return (
      name.includes("terrain") ||
      name.includes("seabed") ||
      name.includes("ground")
    );
  },
  orientationMode: "upright",
  gridSize: null,
  surfaceOffset: 0.02,
};

const constraints: PlacementConstraints = {
  maxObjects: 400,
  minSpacing: 0.8,
  exclusionZones: [
    {
      center: [0, 0, 0],
      radius: 5,
      reason: "Performance stage — keep clear for performers",
    },
  ],
};

const nativeObjects = createMetadataSceneObjectAdapter({
  sceneId: "ocean",
  editableRoles: new Set([
    "coral",
    "flora",
    "rock",
    "reef-structure",
    "decoration",
  ]),
  lockedRoles: new Set(["terrain", "seabed", "stage", "water"]),
  editableNamePatterns: [
    /coral|kelp|seaweed|grass|anemone|starfish|urchin|shell|rock/i,
  ],
  lockedNamePatterns: [
    /terrain|seabed|ground|water|dais|stage|platform|light/i,
  ],
  editableInstancePatterns: [
    /coral|kelp|seaweed|grass|anemone|starfish|urchin|shell|rock/i,
  ],
});

const oceanPlugin: SceneComposerPlugin = {
  sceneId: "ocean",
  displayName: "Ocean Seabed",
  catalog,
  surfaceRules,
  getDefaults: () => [...OCEAN_PLACEMENTS],
  constraints,
  nativeObjects,
};

composerRegistry.register(oceanPlugin);

export { oceanPlugin };
