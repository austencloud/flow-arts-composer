// ── Raw MCP format ──

export interface RawMotion {
  hand: string;
  startLocation: string;
  endLocation: string;
  motionType: string;
  rotationDirection: string;
  startOrientation: string;
  endOrientation: string;
}

export interface RawStep {
  letter: string;
  startPlacement: string;
  endPlacement: string;
  leftMotion: RawMotion;
  rightMotion: RawMotion;
  stepNumber: number;
}

export interface RawSequence {
  word: string;
  steps: RawStep[];
}

function toMotionData(raw: RawMotion, gridMode: GridMode): MotionData {
  return {
    motionType: raw.motionType as MotionType,
    rotationDirection: raw.rotationDirection as RotationDirection,
    startLocation: raw.startLocation as GridLocation,
    endLocation: raw.endLocation as GridLocation,
    turns: 0,
    startOrientation: raw.startOrientation as Orientation,
    endOrientation: raw.endOrientation as Orientation,
    isVisible: true,
    propType: "staff" as PropType,
    arrowLocation: raw.endLocation as GridLocation,
    color: raw.hand as HandSide,
    gridMode,
    arrowPlacementData: { x: 0, y: 0, rotation: 0 },
    propPlacementData: { x: 0, y: 0, rotation: 0 },
  } as unknown as MotionData;
}

function convertRaw(
  raw: RawSequence,
  gridMode: GridMode = "diamond" as GridMode
): MuseumSequenceData {
  const steps: StepData[] = raw.steps
    .filter((s) => s.stepNumber > 0)
    .map((step) => ({
      id: `museum-${raw.word}-${step.stepNumber}`,
      letter: step.letter as Letter,
      startPlacement: step.startPlacement as GridPlacement,
      endPlacement: step.endPlacement as GridPlacement,
      gridMode,
      motions: {
        left: toMotionData(step.leftMotion, gridMode),
        right: toMotionData(step.rightMotion, gridMode),
      },
      stepNumber: step.stepNumber,
      duration: 1,
      leftReversal: false,
      rightReversal: false,
      isBlank: false,
    }));

  const step0 = raw.steps.find((s) => s.stepNumber === 0);
  const startPlacement: PictographData | null = step0
    ? {
        id: `museum-${raw.word}-start`,
        letter: step0.letter as Letter,
        startPlacement: step0.startPlacement as GridPlacement,
        endPlacement: step0.endPlacement as GridPlacement,
        gridMode,
        motions: {
          left: toMotionData(step0.leftMotion, gridMode),
          right: toMotionData(step0.rightMotion, gridMode),
        },
      }
    : null;

  return { word: raw.word, steps, startPlacement };
}

