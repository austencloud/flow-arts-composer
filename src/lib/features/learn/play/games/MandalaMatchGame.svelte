    box-shadow:
      0 0 0 2px var(--game-accent, #fbbf24),
      0 0 20px color-mix(in srgb, var(--game-accent, #fbbf24) 40%, transparent);
  }

  .card-slot.state-incorrect {
    box-shadow: 0 0 0 2px var(--semantic-error, #ef4444);
  }

  .card-slot.state-dimmed {
    opacity: 0.4;
  }

  /* The choreo card paints a white print background + border (paper face);
     inside the game the rendered image is dark, so the white shows as a hard
     frame around every option. Neutralize it — the slot owns the border. */
  .card-slot :global(.choreo-card) {
    --print-bg: transparent;
    border: none;
  }

  @media (prefers-reduced-motion: reduce) {
    .card-slot {
      transition: none;
    }
  }
