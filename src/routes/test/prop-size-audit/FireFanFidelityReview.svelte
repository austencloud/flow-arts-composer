<script lang="ts">
  import { onMount } from "svelte";
  import { generatePropSvg } from "$lib/shared/animation-engine/services/svg-generator";

  interface ReviewFan {
    id: "fire-bare" | "fire-covered" | "lotus" | "flat-grip";
    name: string;
    note: string;
    preview: string;
    renderKey:
      | "fan__fire_bare"
      | "fan__fire_covered"
      | "fan__lotus"
      | "fan__flat-grip";
  }

  const fans: readonly ReviewFan[] = [
    {
      id: "flat-grip",
      name: "Forged Creations Flat Grip Fire",
      note: "Five wicks, crossed spines, a 2-inch spinning ring, and a flat handle between two rear loops.",
      preview: "/images/props/build-previews/fan-flat-grip-complete.webp",
      renderKey: "fan__flat-grip",
    },
    {
      id: "fire-bare",
      name: "DoodleGrip Fire · bare",
      note: "Measured five-wick crown, curved outside rails, welded lattice, and DoodleGrip shell.",
      preview: "/images/props/build-previews/fan-fire-bare-complete.webp",
      renderKey: "fan__fire_bare",
    },
    {
      id: "fire-covered",
      name: "DoodleGrip Fire · covered",
      note: "The fitted crescent sleeve follows the real wick crown instead of replacing it with dots.",
      preview: "/images/props/build-previews/fan-fire-covered-complete.webp",
      renderKey: "fan__fire_covered",
    },
    {
      id: "lotus",
      name: "Home of Poi Medium Lotus",
      note: "Ten traced petal rails, Russian grip geometry, and five independently measured Kevlar rolls.",
      preview: "/images/props/build-previews/fan-lotus-bare-complete.webp?v=6",
      renderKey: "fan__lotus",
    },
  ];

  type MotionRenders = Record<
    ReviewFan["id"],
    { blue: string; red: string } | null
  >;

  let renders = $state<MotionRenders>({
    "flat-grip": null,
    "fire-bare": null,
    "fire-covered": null,
    lotus: null,
  });
  let loadError = $state<string | null>(null);

  onMount(() => {
    const objectUrls: string[] = [];
    let active = true;

    function svgUrl(svg: string): string {
      const url = URL.createObjectURL(
        new Blob([svg], { type: "image/svg+xml;charset=utf-8" })
      );
      objectUrls.push(url);
      return url;
    }

    async function loadProductionRenders(): Promise<void> {
      try {
        for (const fan of fans) {
          const [blue, red] = await Promise.all([
            generatePropSvg(fan.renderKey, "#35a8ff", "dark"),
            generatePropSvg(fan.renderKey, "#ff334f", "dark"),
          ]);
          if (!active) return;
          renders = {
            ...renders,
            [fan.id]: { blue: svgUrl(blue.svg), red: svgUrl(red.svg) },
          };
        }
      } catch (error) {
        if (active) {
          loadError =
            error instanceof Error ? error.message : "The 2D render failed.";
        }
      }
    }

    void loadProductionRenders();
    return () => {
      active = false;
      objectUrls.forEach((url) => URL.revokeObjectURL(url));
    };
  });
</script>

<main class="review-page">
  <header>
    <p class="eyebrow">2D ↔ 3D fidelity gate</p>
    <h1>The same physical fans, flattened cleanly</h1>
    <p class="intro">
      The left side is the current 3D source. The right side is generated by the
      production 2D renderer, with motion color on the frame and physical
      materials preserved on the wicks and cover.
    </p>
  </header>

  {#if loadError}
    <p class="error" role="alert">{loadError}</p>
  {/if}

  <section class="fan-list" aria-label="Fire fan fidelity comparisons">
    {#each fans as fan (fan.id)}
      <article class="fan-card">
        <div class="card-heading">
          <div>
            <span
              >{fan.id === "lotus"
                ? "Traced vector build"
                : "Measured product build"}</span
            >
            <h2>{fan.name}</h2>
          </div>
          <p>{fan.note}</p>
        </div>

        <div class="comparison">
          <figure>
            <figcaption>3D source</figcaption>
            <div class="art-stage source-stage">
              <img src={fan.preview} alt="{fan.name} 3D source" />
            </div>
          </figure>

          <figure aria-busy={!renders[fan.id]}>
            <figcaption>Production 2D · blue / red</figcaption>
            <div class="art-stage two-d-stage">
              {#if renders[fan.id]}
                <img
                  src={renders[fan.id]?.blue}
                  alt="{fan.name} in blue motion color"
                />
                <img
                  src={renders[fan.id]?.red}
                  alt="{fan.name} in red motion color"
                />
              {:else}
                <span class="loading">Rendering measured artwork…</span>
              {/if}
            </div>
          </figure>
        </div>
      </article>
    {/each}
  </section>
</main>

