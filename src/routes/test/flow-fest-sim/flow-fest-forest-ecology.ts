const GRASS_GRID_METERS = 4;
const GRASS_ROUTE_CLEARANCE_METERS = 0.45;
const GROUND_LIFE_ROUTE_CLEARANCE_METERS = 1.2;

/**
 * Adapt the Forest Scene ecology to the measured campground.
 *
 * Forest owns the visual families and wind-ready grass strata. Flow Fest owns
 * every world coordinate: tree centers come from local LiDAR maxima, while
 * ground life is deterministically sampled inside the measured footprint and
 * cut away from every registered route.
 */
export function deriveFlowFestForestEcology(
  contract: FlowFestRuntimeContract,
  terrain: ImportedTerrainDataV2,
  canopy: FlowFestCanopyEvidence,
  campPlan: FlowFestCampPlan | null = null,
  options: FlowFestForestEcologyOptions = {}
): FlowFestForestEcologyLayout {
  const speciesPlan = options.speciesPlan ?? null;
  const routes = mergeEcologyRoutes(contract, campPlan);
  const canopyPeaks = deriveFlowFestCanopyPeaks(
    contract,
    terrain,
    canopy
  ).filter((peak) => !pointNearRoutes(peak.x, peak.z, routes, 3.2));
  const trees = canopyPeaks.map((peak, index): FlowFestForestTreePlacement => {
    const rng = makeRng(
      childSeed(FLOW_FEST_MASTER_SEED, `forest-tree:${peak.x}:${peak.z}`)
    );
    const renderedHeightMeters = clamp(
      peak.measuredHeightMeters * (0.62 + rng() * 0.08),
      7.5,
      19
    );
    const groundY = sampleFlowFestTerrainWorldY(terrain, peak.x, peak.z);
    const cast = castTreeFamily({
      speciesPlan,
      index,
      x: peak.x,
      z: peak.z,
      groundY,
      renderedHeightMeters,
      neighborhoodHighReturnRatio: peak.neighborhoodHighReturnRatio,
      rng,
    });
    return buildTreePlacement(
      peak.x,
      groundY,
      peak.z,
      peak.measuredHeightMeters,
      renderedHeightMeters,
      cast,
      rng
    );
  });
  const measuredCanopyPlacements = trees.length;
  appendCanopyInfillTrees(contract, terrain, canopy, routes, trees, speciesPlan);
  const infillTreePlacements = trees.length - measuredCanopyPlacements;
  const backdropTrees = deriveBackdropTrees(
    contract,
    terrain,
    canopy,
    speciesPlan
  );

  const grass: FlowFestForestGrassPlacement[] = [];
  const groundLife: FlowFestForestGroundLifePlacement[] = [];
  const bounds = contract.surfaceEvidenceProxy.activeBoundsWorldMeters;
  for (
    let gridZ = Math.ceil(bounds.minZ);
    gridZ <= Math.floor(bounds.maxZ);
    gridZ += GRASS_GRID_METERS
  ) {
    for (
      let gridX = Math.ceil(bounds.minX);
      gridX <= Math.floor(bounds.maxX);
      gridX += GRASS_GRID_METERS
    ) {
      const rng = makeRng(
        childSeed(FLOW_FEST_MASTER_SEED, `forest-floor:${gridX}:${gridZ}`)
      );
      const x = gridX + (rng() - 0.5) * 1.65;
      const z = gridZ + (rng() - 0.5) * 1.65;
      if (
        x < bounds.minX ||
        x > bounds.maxX ||
        z < bounds.minZ ||
        z > bounds.maxZ ||
        pointNearRoutes(x, z, routes, GRASS_ROUTE_CLEARANCE_METERS)
      ) {
        continue;
      }

      const canopyOffsetMeters = sampleCanopyOffsetMeters(
        terrain,
        canopy,
        x,
        z
      );
      const shaded = canopyOffsetMeters >= 4;
      const keepProbability = shaded ? 0.84 : 0.66;
      if (rng() > keepProbability) continue;
      const tierRoll = rng();
      const tier: FlowFestForestGrassTier =
        tierRoll < 0.58 ? "base" : tierRoll < 0.9 ? "medium" : "high";
      const species: FlowFestForestGrassSpecies = shaded
        ? "woodland-grass"
        : "summer-sward";
      const baseHeight = species === "woodland-grass" ? 0.42 : 0.32;
      grass.push({
        x,
        y: sampleFlowFestTerrainWorldY(terrain, x, z) + 0.012,
        z,
        rotation: rng() * Math.PI * 2,
        widthMeters: 0.2 + rng() * 0.17,
        heightMeters: baseHeight * (0.72 + rng() * 0.58),
        species,
        tier,
        colorIndex: Math.floor(rng() * 4),
      });

      if (
        shaded &&
        rng() < 0.008 &&
        !pointNearRoutes(x, z, routes, GROUND_LIFE_ROUTE_CLEARANCE_METERS)
      ) {
        groundLife.push({
          x,
          y: sampleFlowFestTerrainWorldY(terrain, x, z),
          z,
          rotation: rng() * Math.PI * 2,
          scale: 0.72 + rng() * 0.58,
          species:
            canopyOffsetMeters > 9 && rng() < 0.32
              ? "woodland-hazel-shrub"
              : "damp-sedge-tussock",
        });
      }
    }
  }
  appendRegisteredZoneGrass(contract, terrain, routes, grass);

  return {
    trees,
    backdropTrees,
    grass,
    groundLife,
    audit: {
      treeRouteIntrusions: trees.filter((placement) =>
        pointNearRoutes(placement.x, placement.z, routes, 3.2)
      ).length,
      grassRouteIntrusions: grass.filter((placement) =>
        pointNearRoutes(
          placement.x,
          placement.z,
          routes,
          GRASS_ROUTE_CLEARANCE_METERS - 0.001
        )
      ).length,
      groundLifeRouteIntrusions: groundLife.filter((placement) =>
        pointNearRoutes(
          placement.x,
          placement.z,
          routes,
          GROUND_LIFE_ROUTE_CLEARANCE_METERS - 0.001
        )
      ).length,
      sourceTreeFamilies: new Set(trees.map((tree) => tree.familyId)).size,
      // Families answer "how many distinct models"; species answers "how many
      // distinct kinds of tree". A site rendered from four seeds of one oak
      // would pass the family count and still look like a plantation.
      sourceTreeSpecies: new Set(
        trees.map(
          (tree) => flowFestTreeFamilyPlan(tree.familyId)?.speciesId ?? "unknown"
        )
      ).size,
      measuredCanopyPlacements,
      infillTreePlacements,
      backdropTreePlacements: backdropTrees.length,
      grassPlacements: grass.length,
      groundLifePlacements: groundLife.length,
    },
  };
}

const BACKDROP_MINIMUM_SPACING_METERS = 10;

/**
 * The measured woodland beyond the property line.
 *
 * Austen, 2026-09-03: "when I look off of the land the trees are nonexistent."
 * The land was never bare — the LiDAR canopy raster covers a full square
 * kilometre and 38.9% of its samples outside the site clear the tall-canopy
 * threshold, against 43.8% inside. Only the site was ever sampled, because
 * every ecology pass reads `activeBoundsWorldMeters`. This one reads the whole
 * raster and subtracts the window the site pass already covered.
 *
 * Spacing is looser than the site's 7.5 m because these trees exist to close
 * the horizon, not to be walked through: the nearest is 150 m from anywhere a
 * player stands, and the ridge lines read as continuous canopy well before the
 * stems resolve. Registered routes and zones are not consulted — none of them
 * reach out here, and the per-sample segment distance is what makes the site
 * pass expensive.
 */
function deriveBackdropTrees(
  contract: FlowFestRuntimeContract,
  terrain: ImportedTerrainDataV2,
  canopy: FlowFestCanopyEvidence,
  speciesPlan: FlowFestTreeSpeciesPlan | null
): FlowFestForestTreePlacement[] {
  return deriveFlowFestCanopyPeaks(contract, terrain, canopy, {
    bounds: terrain.worldBounds,
    excludeBounds: contract.surfaceEvidenceProxy.activeBoundsWorldMeters,
    minimumSpacingMeters: BACKDROP_MINIMUM_SPACING_METERS,
    avoidRegisteredSurfaces: false,
  }).map((peak, index) => {
    const rng = makeRng(
      childSeed(FLOW_FEST_MASTER_SEED, `forest-backdrop:${peak.x}:${peak.z}`)
    );
    const renderedHeightMeters = clamp(
      peak.measuredHeightMeters * (0.62 + rng() * 0.08),
      7.5,
      19
    );
    const groundY = sampleFlowFestTerrainWorldY(terrain, peak.x, peak.z);
    const cast = castTreeFamily({
      speciesPlan,
      index,
      x: peak.x,
      z: peak.z,
      groundY,
      renderedHeightMeters,
      neighborhoodHighReturnRatio: peak.neighborhoodHighReturnRatio,
      rng,
    });
    return buildTreePlacement(
      peak.x,
      groundY,
      peak.z,
      peak.measuredHeightMeters,
      renderedHeightMeters,
      cast,
      rng
    );
  });
}

function buildTreePlacement(
  x: number,
  groundY: number,
  z: number,
  measuredHeightMeters: number,
  renderedHeightMeters: number,
  cast: {
    familyId: FlowFestForestTreeFamilyId;
    trunkHeightMeters: number | null;
  },
  rng: () => number
): FlowFestForestTreePlacement {
  const familyId = cast.familyId;
  const proceduralTrunkHeight = renderedHeightMeters * (0.68 + rng() * 0.05);
  return {
    x,
    y: groundY,
    z,
    rotation: rng() * Math.PI * 2,
    scale: 1,
    colorIndex: 0,
    measuredHeightMeters,
    renderedHeightMeters,
    // This is the COLLISION cylinder's height, not the clear bole under the
    // crown; the visible bole is baked into the family's geometry. A layout
    // that measured a real trunk supplies it here, clamped so a bad row in the
    // layout data cannot produce a knee-high or floating collider.
    trunkHeightMeters: clamp(
      cast.trunkHeightMeters ?? proceduralTrunkHeight,
      1.5,
      renderedHeightMeters
    ),
    // The collision trunk tracks the family's measured bole, so a thick-boled
    // redcedar blocks the avatar at its rendered width instead of at a
    // one-size cylinder it visibly overhangs.
    trunkRadiusMeters: clamp(
      renderedHeightMeters * trunkRadiusRatio(familyId),
      0.2,
      1.9
    ),
    crownRadiusMeters: clamp(
      renderedHeightMeters * (0.27 + rng() * 0.035),
      2.15,
      5.1
    ),
    familyId,
  };
}

const INFILL_GRID_METERS = 8;
const INFILL_MINIMUM_CANOPY_OFFSET_METERS = 5;
const INFILL_MINIMUM_TREE_SPACING_METERS = 4.5;
/** Fraction of qualifying grid cells that actually receive an infill tree. */
const INFILL_ACCEPTANCE = 0.62;

/**
 * The LiDAR peak detector only yields one tree per local canopy maximum, which
 * under-counts closed woodland: broad connected canopy reads as a single peak
 * and the stand renders sparse. This pass walks a jittered grid and plants a
 * tree wherever the canopy raster proves real overhead growth
 * ({@link INFILL_MINIMUM_CANOPY_OFFSET_METERS}) with no measured tree nearby —
 * so density returns only where the survey says trees actually are, never on
 * routes, zones, or open meadow.
 */
function appendCanopyInfillTrees(
  contract: FlowFestRuntimeContract,
  terrain: ImportedTerrainDataV2,
  canopy: FlowFestCanopyEvidence,
  routes: FlowFestRuntimeSegment[],
  trees: FlowFestForestTreePlacement[],
  speciesPlan: FlowFestTreeSpeciesPlan | null
): void {
  const bounds = contract.surfaceEvidenceProxy.activeBoundsWorldMeters;
  const spacingSquared =
    INFILL_MINIMUM_TREE_SPACING_METERS * INFILL_MINIMUM_TREE_SPACING_METERS;
  for (
    let gridZ = Math.ceil(bounds.minZ);
    gridZ <= Math.floor(bounds.maxZ);
    gridZ += INFILL_GRID_METERS
  ) {
    for (
      let gridX = Math.ceil(bounds.minX);
      gridX <= Math.floor(bounds.maxX);
      gridX += INFILL_GRID_METERS
    ) {
      const rng = makeRng(
        childSeed(FLOW_FEST_MASTER_SEED, `forest-infill:${gridX}:${gridZ}`)
      );
      const x = gridX + (rng() - 0.5) * 6.4;
      const z = gridZ + (rng() - 0.5) * 6.4;
      if (x < bounds.minX || x > bounds.maxX) continue;
      if (z < bounds.minZ || z > bounds.maxZ) continue;
      const canopyOffsetMeters = sampleCanopyOffsetMeters(terrain, canopy, x, z);
      if (canopyOffsetMeters < INFILL_MINIMUM_CANOPY_OFFSET_METERS) continue;
      if (pointNearRoutes(x, z, routes, 3.2)) continue;
      if (pointInsideRegisteredZone(contract, x, z)) continue;
      if (
        trees.some((tree) => {
          const deltaX = tree.x - x;
          const deltaZ = tree.z - z;
          return deltaX * deltaX + deltaZ * deltaZ < spacingSquared;
        })
      ) {
        continue;
      }
      if (rng() > INFILL_ACCEPTANCE) continue;

      const renderedHeightMeters = clamp(
        canopyOffsetMeters * (0.62 + rng() * 0.08),
        7.5,
        19
      );
      const groundY = sampleFlowFestTerrainWorldY(terrain, x, z);
      // The gate already proved connected canopy overhead, so the infill point
      // sits inside a stand; the stand-density ratio reflects that.
      const cast = castTreeFamily({
        speciesPlan,
        index: trees.length,
        x,
        z,
        groundY,
        renderedHeightMeters,
        neighborhoodHighReturnRatio: 0.78,
        rng,
      });
      trees.push(
        buildTreePlacement(
          x,
          groundY,
          z,
          canopyOffsetMeters,
          renderedHeightMeters,
          cast,
          rng
        )
      );
    }
  }
}

function pointInsideRegisteredZone(
  contract: FlowFestRuntimeContract,
  x: number,
  z: number
): boolean {
  return contract.zones.some((zone) => {
    const radiusX = zone.radiusMeters ?? zone.searchRadiusXMeters ?? 0;
    const radiusZ = zone.radiusMeters ?? zone.searchRadiusZMeters ?? 0;
    if (radiusX <= 0 || radiusZ <= 0) return false;
    const normalizedX = (x - zone.center.x) / radiusX;
    const normalizedZ = (z - zone.center.z) / radiusZ;
    return normalizedX * normalizedX + normalizedZ * normalizedZ <= 1;
  });
}

function mergeEcologyRoutes(
  contract: FlowFestRuntimeContract,
  campPlan: FlowFestCampPlan | null
): FlowFestRuntimeSegment[] {
  const routes = uniqueFlowFestSurfaceSegments(contract);
  if (!campPlan) return routes;
  const planLines = allFlowFestCampPlanLines(campPlan);
  const byId = new Map(routes.map((route) => [route.id, route]));
  for (const line of planLines)
    byId.set(line.id, flowFestCampPlanLineToRuntimeSegment(line));
  return [...byId.values()];
}

function appendRegisteredZoneGrass(
  contract: FlowFestRuntimeContract,
  terrain: ImportedTerrainDataV2,
  routes: FlowFestRuntimeSegment[],
  grass: FlowFestForestGrassPlacement[]
): void {
  const spacingMeters = 1.05;
  for (const zone of contract.zones) {
    const radiusX = zone.radiusMeters ?? zone.searchRadiusXMeters ?? 0;
    const radiusZ = zone.radiusMeters ?? zone.searchRadiusZMeters ?? 0;
    if (radiusX <= 0 || radiusZ <= 0) continue;
    for (let localZ = -radiusZ; localZ <= radiusZ; localZ += spacingMeters) {
      for (let localX = -radiusX; localX <= radiusX; localX += spacingMeters) {
        for (let tuft = 0; tuft < 3; tuft += 1) {
          const rng = makeRng(
            childSeed(
              FLOW_FEST_MASTER_SEED,
              `zone-grass:${zone.id}:${localX.toFixed(2)}:${localZ.toFixed(2)}:${tuft}`
            )
          );
          const x = zone.center.x + localX + (rng() - 0.5) * 0.86;
          const z = zone.center.z + localZ + (rng() - 0.5) * 0.86;
          const normalizedX = (x - zone.center.x) / radiusX;
          const normalizedZ = (z - zone.center.z) / radiusZ;
          if (
            normalizedX * normalizedX + normalizedZ * normalizedZ > 1 ||
            pointNearRoutes(x, z, routes, GRASS_ROUTE_CLEARANCE_METERS) ||
            rng() > 0.9
          ) {
            continue;
          }
          const tierRoll = rng();
          grass.push({
            x,
            y: sampleFlowFestTerrainWorldY(terrain, x, z) + 0.012,
            z,
            rotation: rng() * Math.PI * 2,
            widthMeters: 0.12 + rng() * 0.1,
            heightMeters: 0.2 + rng() * 0.14,
            species: "summer-sward",
            tier:
              tierRoll < 0.62 ? "base" : tierRoll < 0.92 ? "medium" : "high",
            colorIndex: Math.floor(rng() * 4),
          });
        }
      }
    }
  }
}

/**
 * Habitat casting for the measured woodland. Ground height, rendered height,
 * and the LiDAR neighborhood's high-return ratio sort each placement into a
 * habitat pool; the families in each pool come straight from the species
 * catalog, so a species added there is cast automatically and no list here can
 * drift out of sync with what was actually baked.
 *
 * A catalog role names a form's ecological home. A pool names which forms this
 * particular site casts in one habitat. They are related but not the same
 * axis, and collapsing them was wrong in two directions: the open-grown role
 * held seven families competing for the eleven sparse-neighborhood placements
 * this closed woodlot produces, so three of them never rendered at all, and
 * the understory role holds exactly one species, so every one of the 237
 * small trees came out a boxelder.
 *
 * The high-return ratio is the light measurement that separates them. Eastern
 * redcedar is the shade-intolerant pioneer of Ohio and Indiana fencerows and
 * old-field margins at ten to fifteen metres, so it is cast where the canopy
 * neighborhood is open. Boxelder is the disturbed-ground volunteer that
 * tolerates a closed neighborhood, so it takes the suppressed small trees.
 * White oak and black walnut keep their wide-crowned open-grown forms for the
 * full-height trees standing clear of the stand.
 *
 * Selection within a pool rotates by placement index plus a stable
 * per-48m-cell phase, so a stand reads as a community rather than a tiling
 * pattern. With 35 generated families across 12 forms — each form calibrated
 * to its own crown spread and clear bole, each variant a different ez-tree
 * seed — no two neighbours share a silhouette.
 */
const FLOW_FEST_DAMP_FAMILIES = flowFestTreeFamiliesForRole("damp");
const FLOW_FEST_STAND_FAMILIES = flowFestTreeFamiliesForRole("stand");
const FLOW_FEST_SNAG_FAMILIES = flowFestTreeFamiliesForRole("snag");

/** Small trees under a closed neighborhood: the disturbed-ground volunteer. */
const FLOW_FEST_SUPPRESSED_FAMILIES =
  flowFestTreeFamiliesForRole("understory");

/** Small trees with light: the light-demanding margin and fencerow pioneer. */
const FLOW_FEST_SCRUB_MARGIN_FAMILIES =
  flowFestTreeFamiliesForSpecies("eastern-redcedar");

/**
 * Full-height trees with room to spread. Derived by set difference so that
 * adding another open-grown form to the catalog reaches this pool without a
 * second list to maintain, while the redcedar forms stay with the light-gap
 * small trees where their ten-to-fifteen-metre stature actually stands.
 */
const FLOW_FEST_OPEN_GROWN_FAMILIES = flowFestTreeFamiliesForRole("open").filter(
  (familyId) => !FLOW_FEST_SCRUB_MARGIN_FAMILIES.includes(familyId)
);

/**
 * A 5x5 LiDAR window, so the ratio moves in steps of 0.04. Above this the
 * neighborhood reads as continuous canopy; at or below it there is a gap.
 */
const CLOSED_NEIGHBORHOOD_RATIO = 0.72;

/**
 * Standing dead wood is habitat punctuation — rare, scattered, never a stand.
 * The snag families are generated with a zero leaf count, so they render as
 * bare wood rather than a live crown on a dead trunk.
 */
const SNAG_PROBABILITY = 0.012;

function chooseTreeFamily(
  renderedHeightMeters: number,
  groundY: number,
  neighborhoodHighReturnRatio: number,
  x: number,
  z: number,
  index: number,
  rng: () => number
): FlowFestForestTreeFamilyId {
  const closedNeighborhood =
    neighborhoodHighReturnRatio > CLOSED_NEIGHBORHOOD_RATIO;
  const families =
    rng() < SNAG_PROBABILITY
      ? FLOW_FEST_SNAG_FAMILIES
      : groundY < 8.5
        ? FLOW_FEST_DAMP_FAMILIES
        : renderedHeightMeters < 10.2
          ? closedNeighborhood
            ? FLOW_FEST_SUPPRESSED_FAMILIES
            : FLOW_FEST_SCRUB_MARGIN_FAMILIES
          : closedNeighborhood
            ? FLOW_FEST_STAND_FAMILIES
            : FLOW_FEST_OPEN_GROWN_FAMILIES;
  const habitatRng = makeRng(
    childSeed(
      FLOW_FEST_MASTER_SEED,
      `forest-habitat:${Math.floor(x / 48)}:${Math.floor(z / 48)}`
    )
  );
  const habitatPhase = Math.floor(habitatRng() * families.length);
  const variation = rng() < 0.28 ? 1 : 0;
  return families[(index + habitatPhase + variation) % families.length]!;
}

/**
 * One tree's casting decision: which generated family renders here, and
 * whether the site layout dictated a trunk height for it.
 *
 * The species plan is consulted first and habitat casting is the fallback, so
 * a layout that has an opinion about one grove still gets ecologically sane
 * trees everywhere else. An assignment naming something the catalog does not
 * contain is a layout bug and throws rather than silently reverting to
 * habitat casting — a silently ignored species id is exactly the failure that
 * would make a derived layout look correct while rendering the wrong woodland.
 */
function castTreeFamily(input: {
  speciesPlan: FlowFestTreeSpeciesPlan | null;
  index: number;
  x: number;
  z: number;
  groundY: number;
  renderedHeightMeters: number;
  neighborhoodHighReturnRatio: number;
  rng: () => number;
}): { familyId: FlowFestForestTreeFamilyId; trunkHeightMeters: number | null } {
  const assignment =
    input.speciesPlan?.resolve({
      index: input.index,
      x: input.x,
      z: input.z,
      groundY: input.groundY,
      renderedHeightMeters: input.renderedHeightMeters,
    }) ?? null;

  if (assignment) {
    const familyId = resolveFlowFestTreeFamilyId(
      assignment.speciesId,
      input.index
    );
    if (!familyId) {
      throw new Error(
        `Flow Fest species plan assigned "${assignment.speciesId}" at (${input.x}, ${input.z}), which is not a species, form, or family in flow-fest-tree-species.ts.`
      );
    }
    return {
      familyId,
      trunkHeightMeters: assignment.trunkHeightMeters ?? null,
    };
  }

  return {
    familyId: chooseTreeFamily(
      input.renderedHeightMeters,
      input.groundY,
      input.neighborhoodHighReturnRatio,
      input.x,
      input.z,
      input.index,
      input.rng
    ),
    trunkHeightMeters: null,
  };
}

function sampleCanopyOffsetMeters(
  terrain: ImportedTerrainDataV2,
  canopy: FlowFestCanopyEvidence,
  x: number,
  z: number
): number {
  const column = Math.round(
    ((x - terrain.worldBounds.minX) /
      (terrain.worldBounds.maxX - terrain.worldBounds.minX)) *
      (canopy.width - 1)
  );
  const row = Math.round(
    ((z - terrain.worldBounds.minZ) /
      (terrain.worldBounds.maxZ - terrain.worldBounds.minZ)) *
      (canopy.height - 1)
  );
  if (column < 0 || row < 0 || column >= canopy.width || row >= canopy.height) {
    return 0;
  }
  const value = canopy.offsetsCentimeters[row * canopy.width + column];
  return value == null || value === 65535 ? 0 : value / 100;
}

function pointNearRoutes(
  x: number,
  z: number,
  routes: FlowFestRuntimeSegment[],
  extraClearanceMeters: number
): boolean {
  return routes.some((route) => {
    const clearance = route.widthMeters / 2 + extraClearanceMeters;
    for (let index = 1; index < route.points.length; index += 1) {
      if (
        distanceToSegment(
          x,
          z,
          route.points[index - 1]!,
          route.points[index]!
        ) <= clearance
      ) {
        return true;
      }
    }
    return false;
  });
}

function distanceToSegment(
  x: number,
  z: number,
  start: FlowFestRuntimePoint,
  end: FlowFestRuntimePoint
): number {
  const deltaX = end.x - start.x;
  const deltaZ = end.z - start.z;
  const lengthSquared = deltaX * deltaX + deltaZ * deltaZ;
  if (lengthSquared === 0) return Math.hypot(x - start.x, z - start.z);
  const progress = Math.max(
    0,
    Math.min(
      1,
      ((x - start.x) * deltaX + (z - start.z) * deltaZ) / lengthSquared
    )
  );
  return Math.hypot(
    x - (start.x + deltaX * progress),
    z - (start.z + deltaZ * progress)
  );
}

function clamp(value: number, minimum: number, maximum: number): number {
  return Math.max(minimum, Math.min(maximum, value));
}
