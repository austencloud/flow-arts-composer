/**
 * Every tree in the sim is generated by `@dgreenheck/ez-tree` and baked to a
 * GLB at build time by `scripts/geospatial/build_flow_fest_eztree_species.ts`.
 * The roster IS the species catalog, so adding a species or a variant is one
 * edit in `flow-fest-tree-species.ts` plus a re-bake, never a hand-kept URL
 * table. This replaced 24 fixed GLBs (four island trees plus twenty
 * conditioned PlantFactory exports) that were reused site-wide and read as
 * repetition at ground level.
 */
export const FLOW_FEST_FOREST_TREE_ASSETS: Record<string, string> =
  Object.fromEntries(
    FLOW_FEST_TREE_FAMILY_PLANS.map((plan) => [
      plan.familyId,
      `/models/flow-fest-sim/ecology/species/${plan.familyId}.glb`,
    ])
  );

/**
 * Every family carries its own mid and far tier, generated by
 * `scripts/geospatial/build_flow_fest_tree_lods.mjs`. The tier GLBs keep the
 * near asset's material names and UVs but no textures; the runtime re-binds
 * the near materials by name, so a tree keeps its identity — same silhouette,
 * same bark, same leaf atlas — at every distance.
 */
function deriveDistanceTierAssets(tier: "mid" | "far") {
  return Object.fromEntries(
    Object.keys(FLOW_FEST_FOREST_TREE_ASSETS).map((familyId) => [
      familyId,
      `/models/flow-fest-sim/ecology/distance-lod/${familyId}-${tier}.glb`,
    ])
  ) as Record<FlowFestForestTreeFamilyId, string>;
}

